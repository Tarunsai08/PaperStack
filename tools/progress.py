#!/usr/bin/env python3
"""Generate PROGRESS.md from content/curriculum/*.json and the article folders.

The curriculum "status" field is the source of truth. This script also cross-checks it
against the files on disk and reports any mismatch.

Usage:
    python tools/progress.py            # write PROGRESS.md and print a summary
    python tools/progress.py --check    # exit 1 if PROGRESS.md is out of date
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "pipeline"))
import build_index as bi  # noqa: E402

ORDER = ["dsa", "cp", "famous-algos", "system-design", "ml", "cs-core"]
PRIO = {"P0": 0, "P1": 1, "P2": 2}


def written_ids() -> dict[str, str]:
    out = {}
    for p in bi.article_files():
        try:
            data, _ = bi.parse_article(p.read_text(encoding="utf-8"))
        except bi.ParseError:
            continue
        out[data.get("id")] = data.get("generated_by", "")
    return out


def next_up(entries: list[dict], done: set[str], track_order: dict[str, int], n: int = 10) -> list[dict]:
    """Planned entries whose prerequisites are written, by priority then path order."""
    ready = [e for e in entries if e["status"] == "planned" and all(p in done for p in e.get("prerequisites", []))]
    ready.sort(key=lambda e: (PRIO.get(e["priority"], 9), track_order.get(e["track"], 99), e["order"]))
    return ready[:n]


def render() -> tuple[str, list[str]]:
    tracks = {t["id"]: t for t in bi.load_tracks()}
    track_order = {k: v["order"] for k, v in tracks.items()}
    curricula = {c["subject"]: c for c in bi.load_curricula()}
    on_disk = written_ids()
    done = set(on_disk)
    problems = []
    lines = [
        "# PaperStack progress",
        "",
        "<!-- Generated by tools/progress.py (npm run progress). Do not edit by hand. -->",
        "",
        "Source of truth: the `status` of each entry in `content/curriculum/<subject>.json`.",
        "Read `HANDOFF.md` first if you are picking this project up.",
        "",
        "## Summary",
        "",
        "| Subject | Written | Needs review | Planned | Total | P0 written |",
        "|---|---|---|---|---|---|",
    ]
    totals = [0, 0, 0, 0]
    for sid in ORDER:
        c = curricula.get(sid)
        if not c:
            continue
        es = c["entries"]
        w = sum(e["status"] == "written" for e in es)
        r = sum(e["status"] == "needs_review" for e in es)
        pl = sum(e["status"] == "planned" for e in es)
        p0 = [e for e in es if e["priority"] == "P0"]
        p0w = sum(e["status"] == "written" for e in p0)
        totals = [totals[0] + w, totals[1] + r, totals[2] + pl, totals[3] + len(es)]
        label = sid + (" (coming soon)" if c.get("status") == "planned" else "")
        lines.append(f"| {label} | {w} | {r} | {pl} | {len(es)} | {p0w}/{len(p0)} |")
        for e in es:
            if e["status"] == "written" and e["id"] not in on_disk:
                problems.append(f"{e['id']} is marked written but has no article file")
            if e["status"] == "planned" and e["id"] in on_disk:
                problems.append(f"{e['id']} has an article but is still marked planned")
    lines.append(f"| **All** | **{totals[0]}** | **{totals[1]}** | **{totals[2]}** | **{totals[3]}** | |")

    pipeline_written = sorted(i for i, g in on_disk.items() if str(g).startswith(("gemini", "groq", "ollama")))
    lines += ["", f"Pipeline-generated articles not yet reviewed (see `REVIEW_LOG.md`): **{len(pipeline_written)}**", ""]

    lines += ["## Next to write", "", "Planned entries whose prerequisites are already written, by priority then path order.", ""]
    for sid in ORDER:
        c = curricula.get(sid)
        if not c or c.get("status") == "planned":
            continue
        nxt = next_up(c["entries"], done, track_order)
        lines.append(f"### {sid}")
        lines.append("")
        if not nxt:
            lines.append("_Nothing ready: every planned entry is waiting on a prerequisite, or the subject is complete._")
        for e in nxt:
            lines.append(f"- [ ] `{e['id']}` ({e['priority']}, {e['kind']}, {e['track']}): {e['title_working']}")
        lines.append("")

    lines += ["## Written so far", ""]
    for sid in ORDER:
        c = curricula.get(sid)
        if not c:
            continue
        ws = [e for e in c["entries"] if e["status"] == "written"]
        if not ws:
            continue
        lines.append(f"<details><summary>{sid}: {len(ws)} written</summary>")
        lines.append("")
        for e in ws:
            lines.append(f"- [x] `{e['id']}` {e['title_working']}")
        lines += ["", "</details>", ""]

    if problems:
        lines += ["## Mismatches to fix", ""] + [f"- {p}" for p in problems] + [""]
    return "\n".join(lines).rstrip() + "\n", problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text, problems = render()
    path = ROOT / "PROGRESS.md"
    if args.check:
        ok = path.exists() and path.read_text(encoding="utf-8") == text
        print("PROGRESS.md is up to date." if ok else "PROGRESS.md is stale: run python tools/progress.py")
        return 0 if ok else 1
    path.write_text(text, encoding="utf-8")
    summary = [l for l in text.splitlines() if l.startswith("| ") and not l.startswith("| Subject") and not l.startswith("|---")]
    print("\n".join(summary))
    for p in problems:
        print("MISMATCH:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
